// Версия в ключе — не формальность. Появились стойка, скрут корпуса,
// мягкость связей и выключатель оружия, а мышцы пересчитаны под желейное
// тело. Сохранённые с прошлой версии числа перетёрли бы новые умолчания
// молча. Меняем ключ вместе со смыслом полей.
const STORAGE_KEY = 'topkong.tuning.v7';

/** Подтянуть сохранённые значения. Настройки переживают перезагрузку —
 *  иначе подбирать ощущения с телефона невозможно. */
export function loadTuning() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return;
    const saved = JSON.parse(raw);
    for (const key of Object.keys(defaults)) {
      if (key in saved && typeof saved[key] === typeof defaults[key]) {
        tuning[key] = saved[key];
      }
    }
  } catch (e) {
    // Приватный режим и заблокированное хранилище — не повод не запускать игру.
  }
}

export function saveTuning() {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(tuning));
  } catch (e) { /* см. выше */ }
}

export function resetTuning() {
  Object.assign(tuning, defaults);
  saveTuning();
}

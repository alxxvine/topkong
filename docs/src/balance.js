import * as THREE from 'three';
import { tuning as T } from 'tk/tuning.js';
import { clamp, clamp01, noiseSigned } from 'tk/mathx.js';
import { S, J } from 'tk/skeleton.js';

// Равновесие.
//
// До этого «стоять ровно» держалось на одном: мышцы тянули каждую частицу
// к цели, а цель была на нужной высоте. Это не равновесие, а марионетка
// на нитках — тело держится, потому что его держат, а не потому что оно
// стоит. Толкни посильнее, и оно поедет юзом, не подставив ногу.
//
// Здесь считается то, от чего равновесие зависит на самом деле.
//
// ТОЧКА ПЕРЕХВАТА. Падать начинают не тогда, когда центр тяжести вышел
// за опору, а раньше — когда за неё вышла точка, в которую центр придёт
// по инерции. Для перевёрнутого маятника она считается точно:
//
//     точка перехвата = центр тяжести + скорость / sqrt(g / высота)
//
// Наклонись, стоя неподвижно, — и устоишь; наклонись на ходу — упадёшь,
// хотя центр тяжести в обоих случаях там же. Разницу видит только эта
// формула, и никакой порог по углу её не заменит.
//
// ОПОРА. Всё, на чём боец стоит: отрезок между стоящими стопами, раздутый
// на ширину среза ноги. Пока точка перехвата внутри — боец устоит сам,
// достаточно доработать корпусом. Вышла наружу — устоять уже нельзя,
// нужно переставлять ногу, и переставлять именно ТУДА.
//
// Отсюда обе стратегии сразу, без единого отдельного правила: близко
// к краю — доводка корпусом, за краем — шаг. Ими же закрываются и толчок
// в спину, и остановка с разбега, и стойка на краю арены.
//
// Ничего из этого не зависит от размеров тела. Длина ноги, вес головы
// и ширина стопы входят в формулы числами и берутся из скелета — поэтому
// на каланчу и на коротышку баланс ложится без единой подгонки.

const _com = new THREE.Vector3();
const _vel = new THREE.Vector3();

/** Расстояние от точки до отрезка. Опора — это отрезок между стопами. */
function distToSegment(px, pz, ax, az, bx, bz) {
  const dx = bx - ax;
  const dz = bz - az;
  const len2 = dx * dx + dz * dz;
  let t = len2 > 1e-9 ? ((px - ax) * dx + (pz - az) * dz) / len2 : 0;
  t = t < 0 ? 0 : t > 1 ? 1 : t;
  return {
    dist: Math.hypot(px - (ax + dx * t), pz - (az + dz * t)),
    x: ax + dx * t,
    z: az + dz * t,
  };
}

export class Balance {
  constructor(fighter) {
    this.f = fighter;

    /** Центр тяжести и его скорость — всё считается от них. */
    this.com = new THREE.Vector3();
    this.comVel = new THREE.Vector3();
    this.prevCom = new THREE.Vector3();
    this.hasPrev = false;

    /** Точка перехвата: куда центр тяжести приедет по инерции. */
    this.capture = new THREE.Vector2();
    /** Ближайшая точка опоры к ней и насколько точка перехвата вне опоры. */
    this.support = new THREE.Vector2();
    this.outside = 0;
    /** Насколько тело завалено: угол оси таз→грудь от вертикали, градусы. */
    this.tilt = 0;

    /** Поправка к скорости ядра — доводка корпусом. Читает локомоция. */
    this.pushX = 0;
    this.pushZ = 0;

    /** Нужен шаг, и вот куда. Читает походка. */
    this.needStep = false;
    this.fallX = 0;
    this.fallZ = 0;

    this.seed = Math.random() * 100;
    this.phase = Math.random() * 100;
  }

  reset() {
    this.hasPrev = false;
    this.outside = 0;
    this.pushX = 0;
    this.pushZ = 0;
    this.needStep = false;
  }

  /** Центр тяжести тела. Дубина считается, только когда она в руке. */
  centerOfMass(out) {
    const p = this.f.body.pos;
    let total = 0;
    out.set(0, 0, 0);
    for (let i = 0; i < p.length; i++) {
      if (i === J.ClubTip && !T.withClub) continue;
      const m = S.mass[i];
      out.addScaledVector(p[i], m);
      total += m;
    }
    return out.divideScalar(Math.max(1e-6, total));
  }

  tick(dt, grounded) {
    const f = this.f;
    const body = f.body;

    this.centerOfMass(_com);
    if (this.hasPrev) {
      // Скорость центра тяжести СГЛАЖИВАЕТСЯ, и без этого баланс не работает.
      //
      // В центр тяжести входят и машущая нога, и болтающиеся руки. Стопа
      // при посадке вцепляется в настил, ей разом гасят скорость — центр
      // от этого дёргается, а точка перехвата, где скорость делится
      // на маленькое число, дёргается вдесятеро сильнее. Замерено:
      // у стоящего на месте бойца она выскакивала за опору на 42 см,
      // и он принимался переступать на ровном месте.
      //
      // Постоянная сглаживания — доля времени переноса: медленнее, и баланс
      // не успеет за настоящим падением.
      _vel.copy(_com).sub(this.prevCom).divideScalar(Math.max(1e-5, dt));
      const k = clamp01(dt / Math.max(1e-3, T.balanceSmooth));
      this.comVel.lerp(_vel, k);
    }
    this.prevCom.copy(_com);
    this.com.copy(_com);
    this.hasPrev = true;

    // Завал корпуса — для отладки и для интерфейса: по нему видно, что
    // тело действительно выпрямляется, а не просто стоит где поставили.
    const hips = body.pos[J.Hips];
    const chest = body.pos[J.Chest];
    const dy = chest.y - hips.y;
    this.tilt = Math.atan2(Math.hypot(chest.x - hips.x, chest.z - hips.z),
      Math.max(1e-4, dy)) * 180 / Math.PI;

    if (!grounded) {
      this.outside = 0;
      this.needStep = false;
      this.pushX = 0;
      this.pushZ = 0;
      return;
    }

    // Точка перехвата. Высота считается над стопами, а не над нулём:
    // на краю арены и на подъёме ноль не там, где настил.
    const footY = Math.min(body.pos[J.FootL].y, body.pos[J.FootR].y);
    const h = Math.max(0.15, _com.y - footY);
    const omega = Math.sqrt(Math.abs(T.gravity) / h);
    this.capture.set(_com.x + this.comVel.x / omega, _com.z + this.comVel.z / omega);

    // Опора: отрезок между стоящими стопами. Маховая нога не держит ничего,
    // и это не мелочь — ровно в тот миг, когда она в воздухе, опора вдвое
    // уже, и именно тогда боец и валится.
    const gait = f.gait;
    const stand = [];
    if (!gait.feet[0].swinging) stand.push(body.pos[J.FootL]);
    if (!gait.feet[1].swinging) stand.push(body.pos[J.FootR]);
    if (stand.length === 0) {
      this.outside = 0;
      this.needStep = false;
      return;
    }
    const a = stand[0];
    const b = stand[stand.length - 1];

    // Куда боец СОБИРАЕТСЯ стоять центром тяжести. Смещение медленное
    // и случайное: без него тело стоит абсолютно неподвижно и читается
    // манекеном. Оно настоящее — тело действительно уходит с центра
    // и действительно себя ловит, а не изображает покачивание поверх позы.
    this.phase += dt;
    // Размах покачивания меряется ПОРОГОМ ШАГА, а не шириной стопы.
    //
    // Это единственная величина, которая тут решает: ровно на столько телу
    // и позволено уехать, прежде чем походка бросится переступать. Мерили
    // сначала стопой — и коротышка с широкой стопой и короткой ногой качался
    // на треть своего порога, сам себя сгонял с места и переступал два раза
    // в секунду, стоя без ввода: замерено, уезжал на 1.35 метра за пять
    // секунд. Порог шага пропорционален ноге, и по нему все тела получают
    // одинаково заметное покачивание, не срываясь в топтание.
    const swayAmp = T.swayAmount * T.stepTrigger * S.LegLength * 0.5;
    const sx = noiseSigned(this.seed, this.phase * T.swayRate) * swayAmp;
    const sz = noiseSigned(this.seed + 37, this.phase * T.swayRate * 0.83) * swayAmp;

    const near = distToSegment(this.capture.x, this.capture.y, a.x, a.z, b.x, b.z);
    this.outside = Math.max(0, near.dist - S.FootPrint);

    // Куда точке перехвата ПОЛАГАЕТСЯ быть.
    //
    // Не над опорой. Ходьба — это управляемое падение: идущий человек
    // всё время валится вперёд и всё время подставляет ногу, и точка
    // перехвата у него обязана убегать вперёд ровно на скорость хода.
    // Требовать от неё стоять над опорой значит требовать стоять на месте:
    // замерено, ход вперёд падал с 1.49 до 1.00 м/с — баланс тормозил
    // бойца тем сильнее, чем быстрее тот шёл.
    //
    // Заказанная скорость входит сюда через ту же формулу маятника, что
    // и сама точка перехвата, поэтому на ровном ходу расхождение нулевое,
    // и подработка не включается вовсе. Включается она ровно тогда, когда
    // боец оказался не там, куда собирался: толкнули, споткнулся,
    // затормозил с разбега.
    const loco = f.locomotion;
    const wx = loco ? loco.wantX : 0;
    const wz = loco ? loco.wantZ : 0;
    const wanted2 = wx * wx + wz * wz;
    this.support.set(near.x + wx / omega + sx, near.z + wz / omega + sz);

    // Доводка корпусом: тянем ядро обратно к опоре. Сила ограничена тем,
    // чего голеностоп физически может: у куклы без стоп это очень немного,
    // и оттого шаг случается рано и часто — как и должно быть у существа,
    // которое стоит на двух срезах картона.
    const ex = this.support.x - this.capture.x;
    const ez = this.support.y - this.capture.y;
    const err = Math.hypot(ex, ez);
    this.error = err;
    const gain = T.balanceGain * omega;
    // Потолок доводки — в естественных единицах маятника: сколько скорости
    // тело может погасить, качнувшись в пределах своей опоры. Приземистый
    // с широкой опорой может больше, длинноногий меньше, и оба получают
    // столько, сколько им положено физикой, без отдельной настройки.
    const cap = T.balancePush * omega * S.FootPrint;
    const push = Math.min(err * gain, cap);
    this.pushX = err > 1e-6 ? ex / err * push : 0;
    this.pushZ = err > 1e-6 ? ez / err * push : 0;

    // Корпусом уже не спастись — нужен шаг, и туда, куда валит. Мерой
    // служит расхождение с ЗАДУМАННЫМ падением, а не с опорой: иначе шаг
    // требовался бы на каждом шагу нормальной ходьбы, где точка перехвата
    // и обязана убегать вперёд.
    // Порогом служит не ширина стопы, а ДЛИНА ШАГА: вопрос не «вышел ли
    // центр за опору» — на ходу он выходит постоянно и это нормально, —
    // а «дотянется ли обычный шаг туда, куда валит». Не дотянется — надо
    // бросать ногу немедленно, не дожидаясь своей очереди.
    const stride = (T.stepReach + T.stepTrigger) * S.LegLength;
    this.needStep = err > stride * T.stepCatch;
    if (this.needStep && err > 1e-6) {
      this.fallX = -ex / err;
      this.fallZ = -ez / err;
    }
  }

  /** Запас устойчивости 0..1: единица — точка перехвата ровно над опорой. */
  get margin() {
    return clamp01(1 - this.outside / Math.max(1e-4, S.FootPrint * 3));
  }
}
